const { contextBridge, ipcRenderer } = require('electron')

contextBridge.exposeInMainWorld('texdesk', {
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: patch => ipcRenderer.invoke('settings:set', patch),
  chooseProject: () => ipcRenderer.invoke('project:choose'),
  listFiles: root => ipcRenderer.invoke('project:list', root),
  reveal: root => ipcRenderer.invoke('project:reveal', root),
  readFile: (root, rel) => ipcRenderer.invoke('file:read', root, rel),
  readFileOptional: (root, rel) => ipcRenderer.invoke('file:read-optional', root, rel),
  deleteAppData: (root, rel) => ipcRenderer.invoke('file:delete-appdata', root, rel),
  writeFile: (root, rel, content) => ipcRenderer.invoke('file:write', root, rel, content),
  writeBinary: (root, rel, base64) => ipcRenderer.invoke('file:write-binary', root, rel, base64),
  importChoose: () => ipcRenderer.invoke('import:choose'),
  importCopyImage: (rel, root, destRel) => ipcRenderer.invoke('import:copy-image', rel, root, destRel),
  compile: (root, mainFile) => ipcRenderer.invoke('compile', root, mainFile),
  cancelCompile: () => ipcRenderer.invoke('compile:cancel'),
  synctex: (root, mainFile, args) => ipcRenderer.invoke('synctex', root, mainFile, args),
  setupStatus: () => ipcRenderer.invoke('setup:status'),
  appInfo: () => ipcRenderer.invoke('app:info'),
  learnFolder: name => ipcRenderer.invoke('learn:folder', name),
  ai: {
    config: () => ipcRenderer.invoke('ai:config'),
    setConfig: patch => ipcRenderer.invoke('ai:set-config', patch),
    setKey: (provider, key) => ipcRenderer.invoke('ai:set-key', provider, key),
    run: (id, req) => ipcRenderer.invoke('ai:run', id, req),
    cancel: id => ipcRenderer.invoke('ai:cancel', id),
    models: provider => ipcRenderer.invoke('ai:models', provider),
    status: () => ipcRenderer.invoke('ai:status'),
    pull: model => ipcRenderer.invoke('ai:pull', model),
    onChunk: cb => ipcRenderer.on('ai:chunk', (_e, id, text) => cb(id, text)),
    onPullProgress: cb => ipcRenderer.on('ai:pull-progress', (_e, model, p) => cb(model, p)),
  },
  research: {
    cite: input => ipcRenderer.invoke('research:cite', input),
    search: query => ipcRenderer.invoke('research:search', query),
  },
  exportSubmission: (root, mainFile, zipPath) => ipcRenderer.invoke('export:submission', root, mainFile, zipPath),
  zotero: {
    status: () => ipcRenderer.invoke('zotero:status'),
    search: query => ipcRenderer.invoke('zotero:search', query),
    exportBib: keys => ipcRenderer.invoke('zotero:export', keys),
    save: payload => ipcRenderer.invoke('zotero:save', payload),
    index: () => ipcRenderer.invoke('zotero:index'),
    retrieve: (question, k, citekeys) => ipcRenderer.invoke('zotero:retrieve', question, k, citekeys),
    onIndexProgress: cb => ipcRenderer.on('zotero:index-progress', (_e, p) => cb(p)),
    storage: () => ipcRenderer.invoke('zotero:storage'),
    missingText: () => ipcRenderer.invoke('zotero:missing-text'),
    pdfBytes: key => ipcRenderer.invoke('zotero:pdf-bytes', key),
    saveText: (key, text) => ipcRenderer.invoke('zotero:save-text', key, text),
  },
  lt: {
    status: () => ipcRenderer.invoke('lt:status'),
    install: () => ipcRenderer.invoke('lt:install'),
    check: (annotation, language) => ipcRenderer.invoke('lt:check', annotation, language),
    onInstallProgress: cb => ipcRenderer.on('lt:install-progress', (_e, p) => cb(p)),
  },
  embed: texts => ipcRenderer.invoke('ai:embed', texts),
  web: {
    abstract: doi => ipcRenderer.invoke('web:abstract', doi),
    evidence: claim => ipcRenderer.invoke('web:evidence', claim),
  },
  onMenu: cb => ipcRenderer.on('menu', (_e, channel) => cb(channel)),
})
